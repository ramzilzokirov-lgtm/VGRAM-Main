package org.telegram.ui;

import android.os.Bundle;

public class VgramPrivacyActivity extends VgramBaseActivity {
    @Override protected void onCreate(Bundle state) {
        super.onCreate(state);
        setupScreen("VGRAM / PRIVACY", "Политика конфиденциальности", "Кратко о том, какие данные обрабатывает клиент.");
        card("Аккаунт и сообщения", "VGRAM использует инфраструктуру Telegram. Авторизация, облачные чаты и синхронизация выполняются серверами Telegram согласно правилам и политике Telegram. VGRAM не является отдельным мессенджер-сервером.");
        card("Локальные настройки", "Выбранный цвет интерфейса, переключатели оформления, список импортированных манифестов плагинов и выбранный баннер профиля хранятся локально на устройстве.");
        card("Плагины", "Импортируемые плагины VGRAM — декларативные манифесты. Приложение не исполняет загруженный из них произвольный код.");
        card("Бейджи", "При подключении к серверу бейджей данные передаются только для запрошенной операции. Не вводи ключ администратора на чужом устройстве и не делись им.");
        card("Сторонние сервисы", "Проверка обновлений и серверные функции могут обращаться к сервисам, указанным в приложении. Их обработка данных регулируется также политиками соответствующих сервисов.");
        card("Важно", "Это собственное краткое описание поведения VGRAM, а не юридическая замена официальной политики Telegram. Перед использованием аккаунта ознакомься с политикой Telegram.");
        addButton(body, "Открыть политику Telegram", () -> {
            try { startActivity(new android.content.Intent(android.content.Intent.ACTION_VIEW, android.net.Uri.parse("https://telegram.org/privacy"))); }
            catch (Exception ignored) { }
        });
    }
}
